"""Generate the Python, TypeScript and Go views of contracts/*.json.

The JSON files are the only place where Living Score constants, the
hexes.geojson property contract, and the metric/pipeline registry are edited.
Every consumer reads generated, committed code so no service has to locate
the repo root at runtime.

Run after editing a contract:  python contracts/codegen.py
CI proves nothing drifted:     make contract-check
"""

from __future__ import annotations

import json
import pprint
from pathlib import Path
from typing import Any

CONTRACTS_DIR = Path(__file__).resolve().parent
ROOT = CONTRACTS_DIR.parent

SCORING_PATH = CONTRACTS_DIR / "scoring.json"
SCHEMA_PATH = CONTRACTS_DIR / "hex-properties.schema.json"
METRICS_PATH = CONTRACTS_DIR / "metrics.json"

PY_OUT = ROOT / "microservices" / "data" / "pipeline" / "generated" / "contract.py"
PY_INIT = ROOT / "microservices" / "data" / "pipeline" / "generated" / "__init__.py"
TS_OUT = ROOT / "frontend" / "src" / "scoring" / "generated" / "contract.ts"
GO_OUT = ROOT / "gen" / "contract" / "contract.go"

BANNER_LINES = [
    "Code generated by contracts/codegen.py. DO NOT EDIT.",
    "Source: contracts/scoring.json, contracts/hex-properties.schema.json, contracts/metrics.json",
]


def load() -> tuple[dict[str, Any], dict[str, Any], dict[str, Any]]:
    scoring = json.loads(SCORING_PATH.read_text(encoding="utf-8"))
    schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
    metrics = json.loads(METRICS_PATH.read_text(encoding="utf-8"))
    return scoring, schema, metrics


def strip_comments(node: Any) -> Any:
    """Drop $comment keys so generated code carries data only."""
    if isinstance(node, dict):
        return {k: strip_comments(v) for k, v in node.items() if k != "$comment"}
    if isinstance(node, list):
        return [strip_comments(v) for v in node]
    return node


def declared_keys(schema: dict[str, Any]) -> list[str]:
    return list(schema.get("properties", {}).keys())


# --- validation of the contract itself --------------------------------------


def check_contract(
    scoring: dict[str, Any],
    schema: dict[str, Any],
    metrics: dict[str, Any] | None = None,
) -> None:
    weights = scoring["objective_weights"]
    total = sum(weights.values())
    if abs(total - 1.0) > 1e-9:
        raise SystemExit(f"objective_weights must sum to 1.0, got {total}")

    groups = scoring["daily_life"]["group_weights"]
    group_total = sum(groups.values())
    if abs(group_total - 1.0) > 1e-9:
        raise SystemExit(f"daily_life.group_weights must sum to 1.0, got {group_total}")

    categories = scoring["daily_life"]["category_weights"]
    if set(categories) != set(groups):
        raise SystemExit(
            "daily_life.category_weights groups must match group_weights: "
            f"{sorted(set(categories) ^ set(groups))}"
        )
    for group, cats in categories.items():
        cat_total = sum(cats.values())
        if abs(cat_total - 1.0) > 1e-9:
            raise SystemExit(
                f"daily_life.category_weights.{group} must sum to 1.0, got {cat_total}"
            )

    for alias, target in scoring["daily_life"]["group_aliases"].items():
        if target not in groups:
            raise SystemExit(
                f"daily_life.group_aliases.{alias} points at unknown group {target}"
            )
    for alias, target in scoring["objective_weight_aliases"].items():
        if target not in weights:
            raise SystemExit(
                f"objective_weight_aliases.{alias} points at unknown pillar {target}"
            )

    known = set(declared_keys(schema))
    for pattern in schema.get("patternProperties", {}):
        prefix = pattern.lstrip("^")
        known.update(k for k in known if k.startswith(prefix))
    for consumer, keys in strip_comments(schema.get("x-consumers", {})).items():
        missing = [
            k for k in keys if k not in known and not _matches_pattern(k, schema)
        ]
        if missing:
            raise SystemExit(
                f"x-consumers.{consumer} reads undeclared properties: {missing}"
            )

    for key in schema.get("required", []):
        if key not in known:
            raise SystemExit(f"required property {key} is not declared in properties")

    if metrics is not None:
        _check_metrics(metrics, schema)


def _check_metrics(metrics: dict[str, Any], schema: dict[str, Any]) -> None:
    steps = [strip_comments(s) for s in metrics.get("steps", [])]
    labels = [s["label"] for s in steps]
    if len(labels) != len(set(labels)):
        raise SystemExit("metrics.json steps must have unique labels")
    ids = [s["id"] for s in steps]
    if len(ids) != len(set(ids)):
        raise SystemExit("metrics.json steps must have unique ids")
    waves = [int(s["wave"]) for s in steps]
    if waves != sorted(waves):
        raise SystemExit("metrics.json steps must be listed in wave order")
    expected_waves = list(range(min(waves), max(waves) + 1)) if waves else []
    if sorted(set(waves)) != expected_waves:
        raise SystemExit(f"metrics.json waves must be contiguous, got {sorted(set(waves))}")

    sheet = strip_comments(metrics.get("hex_fact_sheet", {}))
    for key in [*sheet.get("pillars", {}).values(), *sheet.get("walk_minutes", {}).values(), *sheet.get("scalars", [])]:
        if key not in schema.get("properties", {}) and not _matches_pattern(key, schema):
            raise SystemExit(f"hex_fact_sheet key {key} is not declared in the schema")

    for metric in [strip_comments(m) for m in metrics.get("metrics", [])]:
        score_key = metric.get("score_key")
        if score_key and score_key not in schema.get("properties", {}):
            raise SystemExit(f"metric {metric.get('id')} score_key {score_key} is not in the schema")
        for alias_key in metric.get("alias_keys", []):
            if alias_key not in schema.get("properties", {}):
                raise SystemExit(f"metric {metric.get('id')} alias_key {alias_key} is not in the schema")


def _matches_pattern(key: str, schema: dict[str, Any]) -> bool:
    return any(
        key.startswith(p.lstrip("^")) for p in schema.get("patternProperties", {})
    )


# --- Python ----------------------------------------------------------------


def canonical_daily_life(scoring: dict[str, Any]) -> dict[str, Any]:
    return strip_comments(scoring["daily_life"])


def pipeline_steps(metrics: dict[str, Any]) -> list[dict[str, Any]]:
    """Monolith steps. Map-view services own the steps tagged ``map_service``."""
    steps: list[dict[str, Any]] = []
    for step in metrics.get("steps", []):
        clean = strip_comments(step)
        if clean.get("map_service"):
            continue
        steps.append(clean)
    return steps


def pipeline_waves(metrics: dict[str, Any]) -> list[list[str]]:
    buckets: dict[int, list[str]] = {}
    for step in pipeline_steps(metrics):
        buckets.setdefault(int(step["wave"]), []).append(step["label"])
    return [buckets[i] for i in sorted(buckets)]


def required_cache_files(metrics: dict[str, Any]) -> tuple[str, ...]:
    return tuple(
        step["cache_file"]
        for step in pipeline_steps(metrics)
        if step.get("required_cache") and step.get("cache_file")
    )


def metric_score_props(metrics: dict[str, Any]) -> dict[str, str]:
    out: dict[str, str] = {}
    for metric in [strip_comments(m) for m in metrics.get("metrics", [])]:
        key = metric["paint_key"] if metric.get("paint_key") else metric["score_key"]
        out[metric["id"]] = key
        for alias in metric.get("aliases", []):
            out[alias] = key
    return out


def metric_labels(metrics: dict[str, Any]) -> dict[str, str]:
    out: dict[str, str] = {}
    for metric in [strip_comments(m) for m in metrics.get("metrics", [])]:
        label = metric["label"]
        out[metric["id"]] = label
        for alias in metric.get("aliases", []):
            out[alias] = label
    return out


def metric_types(metrics: dict[str, Any]) -> dict[str, str]:
    return {
        m["id"]: m.get("type", "objective_positive")
        for m in (strip_comments(x) for x in metrics.get("metrics", []))
        if m.get("type")
    }


def metric_meta(metrics: dict[str, Any]) -> dict[str, Any]:
    out: dict[str, Any] = {}
    for metric in [strip_comments(m) for m in metrics.get("metrics", [])]:
        meta = dict(metric.get("meta") or {})
        if not meta:
            continue
        out[metric["id"]] = meta
        for alias in metric.get("aliases", []):
            out.setdefault(alias, meta)
    return out


def map_view_metrics(metrics: dict[str, Any]) -> tuple[str, ...]:
    """Overlay metrics shown as extra map-colour modes (not Living Score)."""
    out: list[str] = []
    for metric in (strip_comments(x) for x in metrics.get("metrics", [])):
        if not metric.get("map_view"):
            continue
        if metric.get("enabled") is False:
            continue
        out.append(metric["id"])
    return tuple(out)


def render_python(
    scoring: dict[str, Any],
    schema: dict[str, Any],
    metrics: dict[str, Any] | None = None,
) -> str:
    def lit(value: Any) -> str:
        return pprint.pformat(value, indent=4, width=96, sort_dicts=False)

    daily = canonical_daily_life(scoring)
    body = [
        '"""' + BANNER_LINES[0],
        "",
        BANNER_LINES[1],
        '"""',
        "from __future__ import annotations",
        "",
        "from typing import Any",
        "",
        f"SCORE_METHOD_VERSION = {scoring['score_method_version']!r}",
        f"PIPELINE_VERSION = {schema['x-pipeline-version']!r}",
        "",
        f"OBJECTIVE_WEIGHTS: dict[str, float] = {lit(scoring['objective_weights'])}",
        "",
        f"OBJECTIVE_WEIGHT_ALIASES: dict[str, str] = {lit(scoring['objective_weight_aliases'])}",
        "",
        f"INFORMATIONAL_PILLARS: dict[str, float] = {lit(strip_comments(scoring['informational_pillars']))}",
        "",
        f"DAILY_LIFE_GROUP_WEIGHTS: dict[str, float] = {lit(daily['group_weights'])}",
        "",
        f"DAILY_LIFE_GROUP_ALIASES: dict[str, str] = {lit(daily['group_aliases'])}",
        "",
        f"DAILY_LIFE_CATEGORY_WEIGHTS: dict[str, dict[str, float]] = {lit(daily['category_weights'])}",
        "",
        f"WALK_MINUTE_BANDS: dict[str, list[list[float]]] = {lit(strip_comments(scoring['walk_minute_bands']))}",
        "",
        f"HEX_PROPERTIES_SCHEMA: dict[str, Any] = {lit(strip_comments(schema))}",
        "",
        f"REQUIRED_HEX_PROPERTIES: tuple[str, ...] = {lit(tuple(schema.get('required', [])))}",
        "",
        f"DECLARED_HEX_PROPERTIES: tuple[str, ...] = {lit(tuple(declared_keys(schema)))}",
        "",
        f"CONSUMER_HEX_PROPERTIES: dict[str, tuple[str, ...]] = {lit({k: tuple(v) for k, v in strip_comments(schema['x-consumers']).items()})}",
        "",
    ]
    if metrics is not None:
        sheet = strip_comments(metrics.get("hex_fact_sheet", {}))
        body.extend(
            [
                f"PIPELINE_STEPS: tuple[dict[str, Any], ...] = {lit(tuple(pipeline_steps(metrics)))}",
                "",
                f"PIPELINE_WAVES: tuple[tuple[str, ...], ...] = {lit(tuple(tuple(w) for w in pipeline_waves(metrics)))}",
                "",
                f"REQUIRED_CACHE_FILES: tuple[str, ...] = {lit(required_cache_files(metrics))}",
                "",
                f"METRIC_SCORE_PROPS: dict[str, str] = {lit(metric_score_props(metrics))}",
                "",
                f"METRIC_LABELS: dict[str, str] = {lit(metric_labels(metrics))}",
                "",
                f"METRIC_TYPES: dict[str, str] = {lit(metric_types(metrics))}",
                "",
                f"METRIC_META: dict[str, Any] = {lit(metric_meta(metrics))}",
                "",
                f"MAP_VIEW_METRICS: tuple[str, ...] = {lit(map_view_metrics(metrics))}",
                "",
                f"HEX_PILLAR_KEYS: dict[str, str] = {lit(sheet.get('pillars', {}))}",
                "",
                f"HEX_WALK_MINUTE_KEYS: dict[str, str] = {lit(sheet.get('walk_minutes', {}))}",
                "",
                f"HEX_SCALAR_KEYS: tuple[str, ...] = {lit(tuple(sheet.get('scalars', ())))}",
                "",
            ]
        )
    return "\n".join(body)


# --- TypeScript -------------------------------------------------------------

TS_SCALARS = {
    "string": "string",
    "number": "number",
    "integer": "number",
    "boolean": "boolean",
    "null": "null",
}


def ts_type_for(spec: dict[str, Any], schema: dict[str, Any]) -> str:
    ref = spec.get("$ref")
    if ref:
        name = ref.rsplit("/", 1)[-1]
        spec = schema["$defs"][name]
    if "enum" in spec:
        parts = ["null" if v is None else json.dumps(v) for v in spec["enum"]]
        return " | ".join(dict.fromkeys(parts))
    raw = spec.get("type", "unknown")
    types = raw if isinstance(raw, list) else [raw]
    mapped = dict.fromkeys(TS_SCALARS.get(t, "unknown") for t in types)
    return " | ".join(mapped)


def _ts_number(value: float) -> str:
    """Keep 0.20 readable as 0.2 while never emitting scientific notation."""
    text = repr(float(value))
    return text.removesuffix(".0")


def _ts_flat_map(values: dict[str, float]) -> str:
    inner = "\n".join(f"  {k}: {_ts_number(v)}," for k, v in values.items())
    return "{\n" + inner + "\n}"


def _ts_flat_string_map(values: dict[str, str]) -> str:
    inner = "\n".join(f"  {k}: '{v}'," for k, v in values.items())
    return "{\n" + inner + "\n}"


def _ts_nested_map(values: dict[str, dict[str, float]]) -> str:
    rows = []
    for group, cats in values.items():
        pairs = ", ".join(f"{k}: {_ts_number(v)}" for k, v in cats.items())
        rows.append(f"  {group}: {{ {pairs} }},")
    return "{\n" + "\n".join(rows) + "\n}"


def _ts_bands(values: dict[str, list[list[float]]]) -> str:
    rows = []
    for name, knots in values.items():
        pairs = ", ".join(f"[{_ts_number(x)}, {_ts_number(y)}]" for x, y in knots)
        rows.append(f"  {name}: [{pairs}],")
    return "{\n" + "\n".join(rows) + "\n}"


def render_typescript(
    scoring: dict[str, Any],
    schema: dict[str, Any],
    metrics: dict[str, Any] | None = None,
) -> str:
    daily = canonical_daily_life(scoring)

    def quoted_list(values: list[str], indent: str = "  ") -> str:
        return "\n".join(f"{indent}'{v}'," for v in values)

    prop_lines: list[str] = []
    for key, spec in schema["properties"].items():
        desc = spec.get("description")
        if desc:
            prop_lines.append(f"  /** {desc} */")
        prop_lines.append(f"  {key}?: {ts_type_for(spec, schema)};")

    pillar_keys = list(scoring["objective_weights"].keys())

    lines = [
        f"// {BANNER_LINES[0]}",
        f"// {BANNER_LINES[1]}",
        "",
        "export type ObjectivePillarKey =",
        "\n".join(f"  | '{k}'" for k in pillar_keys) + ";",
        "",
        f"export const SCORE_METHOD_VERSION = '{scoring['score_method_version']}' as const;",
        f"export const PIPELINE_VERSION = {schema['x-pipeline-version']} as const;",
        "",
        "export const OBJECTIVE_PILLAR_KEYS: ObjectivePillarKey[] = [",
        quoted_list(pillar_keys),
        "];",
        "",
        "export const OBJECTIVE_WEIGHTS: Record<ObjectivePillarKey, number> = "
        + _ts_flat_map(scoring["objective_weights"])
        + ";",
        "",
        "/** Legacy pillar names still emitted by the pipeline. */",
        "export const OBJECTIVE_WEIGHT_ALIASES: Record<string, ObjectivePillarKey> = "
        + _ts_flat_string_map(scoring["objective_weight_aliases"])
        + ";",
        "",
        "/** Exported and shown in the UI, weighted 0 in the objective score. */",
        "export const INFORMATIONAL_PILLARS: Record<string, number> = "
        + _ts_flat_map(strip_comments(scoring["informational_pillars"]))
        + ";",
        "",
        "export const DAILY_LIFE_GROUP_WEIGHTS: Record<string, number> = "
        + _ts_flat_map(daily["group_weights"])
        + ";",
        "",
        "export const DAILY_LIFE_GROUP_ALIASES: Record<string, string> = "
        + _ts_flat_string_map(daily["group_aliases"])
        + ";",
        "",
        "export const DAILY_LIFE_CATEGORY_WEIGHTS: Record<string, Record<string, number>> = "
        + _ts_nested_map(daily["category_weights"])
        + ";",
        "",
        "export const WALK_MINUTE_BANDS: Record<string, [number, number][]> = "
        + _ts_bands(strip_comments(scoring["walk_minute_bands"]))
        + ";",
        "",
        "/** Properties written by the pipeline into hexes.geojson features. */",
        "export type HexProperties = {",
        "\n".join(prop_lines),
        "  /** dn_* / dl_* / center_min_* / wq_* / uf_* / wb_* and future additions. */",
        "  [key: string]: unknown;",
        "};",
        "",
        "export const DECLARED_HEX_PROPERTIES: string[] = [",
        quoted_list(declared_keys(schema)),
        "];",
        "",
        "export const REQUIRED_HEX_PROPERTIES: string[] = [",
        quoted_list(list(schema.get("required", []))),
        "];",
        "",
        "export const FRONTEND_HEX_PROPERTIES: string[] = [",
        quoted_list(list(strip_comments(schema["x-consumers"])["frontend-scoring"])),
        "];",
        "",
    ]
    if metrics is not None:
        pillar_labels = {
            m["id"]: m["label"]
            for m in (strip_comments(x) for x in metrics.get("metrics", []))
            if m.get("kind") in {"pillar", "informational"}
        }
        for metric in (strip_comments(x) for x in metrics.get("metrics", [])):
            if metric.get("kind") not in {"pillar", "informational"}:
                continue
            for alias in metric.get("aliases", []):
                pillar_labels[alias] = metric["label"]
        lines.extend(
            [
                "export const SCORE_PROPS: Record<string, string> = "
                + _ts_flat_string_map(metric_score_props(metrics))
                + ";",
                "",
                "export const METRIC_LABELS: Record<string, string> = "
                + _ts_flat_string_map(metric_labels(metrics))
                + ";",
                "",
                "export const PILLAR_LABELS: Record<string, string> = "
                + _ts_flat_string_map(pillar_labels)
                + ";",
                "",
                "export const MAP_VIEW_METRICS: string[] = [",
                quoted_list(list(map_view_metrics(metrics))),
                "];",
                "",
            ]
        )
    return "\n".join(lines)


# --- Go ---------------------------------------------------------------------


def render_go(
    scoring: dict[str, Any],
    schema: dict[str, Any],
    metrics: dict[str, Any] | None = None,
) -> str:
    consumers = strip_comments(schema["x-consumers"])

    def go_string_slice(values: list[str], indent: str = "\t") -> str:
        return "\n".join(f'{indent}"{v}",' for v in values)

    def go_string_map(values: dict[str, str], indent: str = "\t") -> str:
        return "\n".join(f'{indent}"{k}": "{v}",' for k, v in values.items())

    weight_entries = "\n".join(
        f'\t"{k}": {v},' for k, v in scoring["objective_weights"].items()
    )

    lines = [
        f"// {BANNER_LINES[0]}",
        f"// {BANNER_LINES[1]}",
        "",
        "// Package contract exposes the shared Living Score contract to Go services.",
        "package contract",
        "",
        f'const ScoreMethodVersion = "{scoring["score_method_version"]}"',
        "",
        f"const PipelineVersion = {schema['x-pipeline-version']}",
        "",
        "// ObjectiveWeights are the pillar weights of the objective Living Score.",
        "var ObjectiveWeights = map[string]float64{",
        weight_entries,
        "}",
        "",
        "// DeclaredHexProperties lists every property the pipeline may export.",
        "var DeclaredHexProperties = []string{",
        go_string_slice(declared_keys(schema)),
        "}",
        "",
        "// RequiredHexProperties lists properties present on every exported feature.",
        "var RequiredHexProperties = []string{",
        go_string_slice(list(schema.get("required", []))),
        "}",
        "",
        "// HexServiceProperties lists the properties hex-svc reads into its fact sheet.",
        "var HexServiceProperties = []string{",
        go_string_slice(list(consumers["go-hex-svc"])),
        "}",
        "",
    ]
    if metrics is not None:
        sheet = strip_comments(metrics.get("hex_fact_sheet", {}))
        lines.extend(
            [
                "// HexPillarKeys maps fact-sheet labels to hex property names.",
                "var HexPillarKeys = map[string]string{",
                go_string_map(sheet.get("pillars", {})),
                "}",
                "",
                "// HexWalkMinuteKeys maps walk-minute labels to hex property names.",
                "var HexWalkMinuteKeys = map[string]string{",
                go_string_map(sheet.get("walk_minutes", {})),
                "}",
                "",
                "// HexScalarKeys are the non-map fields copied into the fact sheet.",
                "var HexScalarKeys = []string{",
                go_string_slice(list(sheet.get("scalars", []))),
                "}",
                "",
            ]
        )
    return "\n".join(lines)


# --- driver -----------------------------------------------------------------


def write(path: Path, content: str) -> bool:
    path.parent.mkdir(parents=True, exist_ok=True)
    previous = path.read_text(encoding="utf-8") if path.exists() else None
    if previous == content:
        return False
    path.write_text(content, encoding="utf-8")
    return True


def main() -> None:
    scoring, schema, metrics = load()
    check_contract(scoring, schema, metrics)

    changed = [
        path
        for path, content in (
            (PY_INIT, '"""Generated contract views. Do not edit by hand."""\n'),
            (PY_OUT, render_python(scoring, schema, metrics)),
            (TS_OUT, render_typescript(scoring, schema, metrics)),
            (GO_OUT, render_go(scoring, schema, metrics)),
        )
        if write(path, content)
    ]
    if changed:
        for path in changed:
            print(f"wrote {path.relative_to(ROOT)}")
    else:
        print("contract code already up to date")


if __name__ == "__main__":
    main()
