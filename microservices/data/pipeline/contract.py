"""Pipeline-side view of contracts/*.json plus export validation.

Constants come from :mod:`pipeline.generated.contract`, which is generated by
``contracts/codegen.py``. Nothing in this package may redefine a weight or a
band: edit ``contracts/scoring.json`` and regenerate instead.

The validator implements the JSON Schema subset actually used by
``contracts/hex-properties.schema.json`` (type, enum, minimum, maximum,
required, properties, patternProperties, $ref/$defs). That keeps the export
path dependency-free; ``jsonschema`` is not needed at runtime.
"""

