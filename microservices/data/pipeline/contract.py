# --- schema validation ------------------------------------------------------


def _resolve(spec: dict[str, Any], schema: dict[str, Any]) -> dict[str, Any]:
    ref = spec.get("$ref")
    if not ref:
        return spec
    return schema.get("$defs", {}).get(ref.rsplit("/", 1)[-1], {})


def _type_matches(value: Any, expected: str) -> bool:
    if expected == "null":
        return value is None
    if expected == "boolean":
        return isinstance(value, bool)
    if expected == "string":
        return isinstance(value, str)
    if expected == "integer":
        return isinstance(value, numbers.Integral) and not isinstance(value, bool)
    if expected == "number":
        return isinstance(value, numbers.Real) and not isinstance(value, bool)
    if expected == "object":
        return isinstance(value, dict)
    if expected == "array":
        return isinstance(value, (list, tuple))
    return True


def _check_value(key: str, value: Any, spec: dict[str, Any], schema: dict[str, Any]) -> list[str]:
    spec = _resolve(spec, schema)
    errors: list[str] = []

    raw_type = spec.get("type")
    if raw_type is not None:
        expected = raw_type if isinstance(raw_type, list) else [raw_type]
        if not any(_type_matches(value, t) for t in expected):
            errors.append(f"{key}: expected {'|'.join(expected)}, got {type(value).__name__}")
            return errors

    if "enum" in spec and value not in spec["enum"]:
        errors.append(f"{key}: {value!r} not in {spec['enum']}")

    if value is not None and isinstance(value, numbers.Real) and not isinstance(value, bool):
        low = spec.get("minimum")
        high = spec.get("maximum")
        if low is not None and float(value) < float(low):
            errors.append(f"{key}: {value} < minimum {low}")
        if high is not None and float(value) > float(high):
            errors.append(f"{key}: {value} > maximum {high}")

    return errors


def validate_feature_properties(props: dict[str, Any]) -> list[str]:
    """Return a list of contract violations for one feature's properties."""
    schema = HEX_PROPERTIES_SCHEMA
    declared: dict[str, Any] = schema.get("properties", {})
    patterns = [(re.compile(pattern), spec) for pattern, spec in schema.get("patternProperties", {}).items()]

    errors: list[str] = []
    for key in schema.get("required", []):
        if key not in props:
            errors.append(f"{key}: required property missing")

    for key, value in props.items():
        spec = declared.get(key)
        if spec is not None:
            errors.extend(_check_value(key, value, spec, schema))
            continue
        for pattern, pattern_spec in patterns:
            if pattern.search(key):
                errors.extend(_check_value(key, value, pattern_spec, schema))
                break
    return errors


def validate_features(features: list[dict[str, Any]], *, sample: int = 25) -> list[str]:
    """Validate a sample of features plus a whole-collection required-key sweep.

    Per-feature type checks on thousands of hexes are wasted work: the pipeline
    builds every feature from the same code path. Checking a spread-out sample
    catches schema drift while staying cheap enough to run on every export.
    """
    if not features:
        return ["feature collection is empty"]

    errors: list[str] = []
    step = max(1, len(features) // max(1, sample))
    for index in range(0, len(features), step):
        props = features[index].get("properties") or {}
        for error in validate_feature_properties(props):
            errors.append(f"feature[{index}] {error}")
    return errors


class ContractError(RuntimeError):
    """Raised when an export would violate the hex property contract."""


def assert_features_valid(features: list[dict[str, Any]], *, context: str = "export") -> None:
    errors = validate_features(features)
    if errors:
        head = "\n  ".join(errors[:15])
        more = f"\n  … and {len(errors) - 15} more" if len(errors) > 15 else ""
        raise ContractError(f"{context} violates contracts/hex-properties.schema.json:\n  {head}{more}")
